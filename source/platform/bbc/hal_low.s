; BBC Master port - the only HAL code that runs while ACCCON.X = 1 (the CPU sees the shadow
; screen at &3000-&7FFF) so it must sit in low RAM, plus the tables the renderer reads.
; Interrupts are off for the whole of each critical section, so the vsync handler can never run
; while the wrong bank is paged in or while MID is invisible.

.segment "LOW"

.macro GFX_ENTER
        sei
        lda #GFXBANK
        sta ROMSEL_SH
        sta ROMSEL
        lda ACCCON
        ora #ACC_X
        sta ACCCON
.endmacro

.macro GFX_LEAVE
        lda ACCCON
        and #<~ACC_X
        sta ACCCON
        lda #DATABANK
        sta ROMSEL_SH
        sta ROMSEL
        cli
.endmacro

; draw one cell (G_GLY, G_MASK, P_D0, P_D8 set up)
HAL_CELL_CRIT:
        GFX_ENTER
        jsr GFX_CELL
        GFX_LEAVE
        rts

; draw one cell with sprites composited over it (G_CX, G_CY, G_SM set up too)
HAL_CELLSPR_CRIT:
        GFX_ENTER
        jsr GFX_CELLSPR
        GFX_LEAVE
        rts

.include "palette.inc"          ; PHYS / CMAP / CMASK, generated by tools/make_data.py

; copy a cached tile image (3 strips of 48 bytes, bank BL_BANK at P_S) to the screen at P_D0 (strips 640 apart).
; The three strips are copied together by one loop whose six operands are patched per tile (this code is in RAM):
; 9 cycles a byte plus a small per-tile set-up, instead of 13 a byte with (zp),y.
HAL_BLIT_CRIT:
        sei
        lda P_S                 ; source strips: P_S, +48, +96
        sta BS0+1
        clc
        adc #48
        sta BS1+1
        lda P_S+1
        sta BS0+2
        adc #0
        sta BS1+2
        lda BS1+1
        clc
        adc #48
        sta BS2+1
        lda BS1+2
        adc #0
        sta BS2+2
        lda P_D0                ; destination strips: P_D0, +640, +1280
        sta BD0+1
        clc
        adc #<640
        sta BD1+1
        lda P_D0+1
        sta BD0+2
        adc #>640
        sta BD1+2
        lda BD1+1
        clc
        adc #<640
        sta BD2+1
        lda BD1+2
        adc #>640
        sta BD2+2
        lda BL_BANK
        sta ROMSEL_SH
        sta ROMSEL
        lda ACCCON
        ora #ACC_X
        sta ACCCON
        ldx #47
BS0:    lda $FFFF,x
BD0:    sta $FFFF,x
BS1:    lda $FFFF,x
BD1:    sta $FFFF,x
BS2:    lda $FFFF,x
BD2:    sta $FFFF,x
        dex
        bpl BS0
        lda ACCCON
        and #<~ACC_X
        sta ACCCON
        lda #DATABANK
        sta ROMSEL_SH
        sta ROMSEL
        cli
        rts

; overview map: set (G_V = 1) or clear (G_V = 0) the pixels in mask G_M of the screen byte at P_D0 (white)
HAL_PIXEL_CRIT:
        sei
        lda ACCCON
        ora #ACC_X
        sta ACCCON
        ldy #0
        lda G_M
        eor #$FF
        and (P_D0),y
        sta G_TMP
        lda G_V
        beq @st
        lda G_M                 ; white = both planes, so the coverage mask is the value
        ora G_TMP
        sta G_TMP
@st:    lda G_TMP
        sta (P_D0),y
        lda ACCCON
        and #<~ACC_X
        sta ACCCON
        cli
        rts

; tables shared by MID (building sprite records) and the renderer
BITS:   .byte 1,2,4,8,16,32,64,128
V1TAB:  .byte $00,$0C,$C0,$CC   ; logical colour v -> slot-1 pixel pair (planes: v bit 1 = high nibble)
V2TAB:  .byte $00,$03,$30,$33
; cell row / first column of every group of 4 cells (40 cells per row, so a group never straddles rows)
ROWTAB: .repeat CELLS / 4, g
        .byte g / 10
        .endrepeat
COLTAB: .repeat CELLS / 4, g
        .byte (g * 4) .mod 40
        .endrepeat
