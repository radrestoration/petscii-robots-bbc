; BBC Master port - the only HAL code that runs while ACCCON.X = 1 (the CPU sees the shadow
; screen at &3000-&7FFF) so it must sit in low RAM, plus the tables the renderer reads.
; Interrupts are off for the whole of each critical section, so the vsync handler can never run
; while the wrong bank is paged in or while MID is invisible.

.segment "LOW"

.macro GFX_ENTER
        sei
        lda #GFXBANK
        sta ROMSEL_SH
        sta ROMSEL
        lda ACCCON
        ora #ACC_X
        sta ACCCON
.endmacro

.macro GFX_LEAVE
        lda ACCCON
        and #<~ACC_X
        sta ACCCON
        lda #DATABANK
        sta ROMSEL_SH
        sta ROMSEL
        cli
.endmacro

; draw one cell (G_GLY, G_MASK, P_D0, P_D8 set up)
HAL_CELL_CRIT:
        GFX_ENTER
        jsr GFX_CELL
        GFX_LEAVE
        rts

; draw one cell with sprites composited over it (G_CX, G_CY, G_SM set up too)
HAL_CELLSPR_CRIT:
        GFX_ENTER
        jsr GFX_CELLSPR
        GFX_LEAVE
        rts

.include "palette.inc"          ; PHYS / CMAP / CMASK, generated by tools/make_data.py

; copy a cached tile image (3 strips of 48 bytes, bank BL_BANK at P_S) to the screen at P_D0 (strips 640 apart)
HAL_BLIT_CRIT:
        sei
        lda BL_BANK
        sta ROMSEL_SH
        sta ROMSEL
        lda ACCCON
        ora #ACC_X
        sta ACCCON
        ldx #3
@strip: ldy #47
@c:     lda (P_S),y
        sta (P_D0),y
        dey
        bpl @c
        lda P_S
        clc
        adc #48
        sta P_S
        bcc :+
        inc P_S+1
:       lda P_D0
        clc
        adc #<640
        sta P_D0
        lda P_D0+1
        adc #>640
        sta P_D0+1
        dex
        bne @strip
        lda ACCCON
        and #<~ACC_X
        sta ACCCON
        lda #DATABANK
        sta ROMSEL_SH
        sta ROMSEL
        cli
        rts

; tables shared by MID (building sprite records) and the renderer
BITS:   .byte 1,2,4,8,16,32,64,128
V1TAB:  .byte $00,$0C,$C0,$CC   ; logical colour v -> slot-1 pixel pair (planes: v bit 1 = high nibble)
V2TAB:  .byte $00,$03,$30,$33
; cell row / first column of every group of 4 cells (40 cells per row, so a group never straddles rows)
ROWTAB: .repeat CELLS / 4, g
        .byte g / 10
        .endrepeat
COLTAB: .repeat CELLS / 4, g
        .byte (g * 4) .mod 40
        .endrepeat
