	BNE	IRQ32
	LDA	#7
	STA	SPRITECOLTIMER
	LDY	SPRITECOLSTATE
	LDA	SPRITECOLCHART,Y
	STA	VIC+$27	;SPRITE 0 COLOR REGISTER
	;STA	$D028	;SPRITE 1 COLOR REGISTER
	INY
	CPY	#8
	BNE	IRQ31
	LDY	#0
