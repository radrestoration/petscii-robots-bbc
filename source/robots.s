;This routine checks all units from 0 to 31 and figures out if it should be dislpayed
;on screen, and then grabs that unit's tile and stores it in the MAP_PRECALC array
;so that when the window is drawn, it does not have to search for units during the
;draw, speeding up the display routine.
MAP_PRE_CALCULATE:
	;CLEAR OLD BUFFER
	LDA	#0
	LDY	#0
PREC0:	STA	MAP_PRECALC,Y
	INY
	CPY	#WIN_W*WIN_H
	BNE	PREC0
	LDX	#1	;In this version, we don't draw the player here.
PREC1:	;CHECK THAT UNIT EXISTS
	LDA	UNIT_TYPE,X
	CMP	#0
	BEQ	PREC5
	;CHECK HORIZONTAL POSITION
	LDA	UNIT_LOC_X,X
	CMP	MAP_WINDOW_X
	BCC	PREC5
	LDA	MAP_WINDOW_X
	CLC
	ADC	#10
	CMP	UNIT_LOC_X,X
	BCC	PREC5
	;NOW CHECK VERTICAL
	LDA	UNIT_LOC_Y,X
	SEC
	SBC	MAP_WINDOW_Y	;BBC: 9 tiles tall; wrap-safe if the window starts above the map
	CMP	#WIN_H
	BCS	PREC5
	;Unit found in map window, now add that unit's
	;tile to the precalc map.
PREC2:	LDA	UNIT_LOC_Y,X
	SEC
	SBC	MAP_WINDOW_Y
	TAY
	LDA	UNIT_LOC_X,X
	SEC
	SBC	MAP_WINDOW_X
	CLC
	ADC	PRECALC_ROWS,Y	
	TAY
	LDA	UNIT_TILE,X
	CMP	#130	;is it a bomb
	BEQ	PREC6
	CMP	#134	;is it a magnet?
	BEQ	PREC6
PREC4:	STA	MAP_PRECALC,Y
PREC5:	;continue search
	INX	
	CPX	#32
	BNE	PREC1
	RTS
PREC6:	;What to do in case of bomb or magnet that should
	;go underneath the unit or robot.
	LDA	MAP_PRECALC,Y
	CMP	#0
	BNE	PREC5
	LDA	UNIT_TILE,X
	JMP	PREC4		

PRECALC_ROWS:	.byte 0,11,22,33,44,55,66,77,88

;This routine is where the MAP is displayed on the screen
;This is a temporary routine, taken from the map editor.
DRAW_MAP_WINDOW:
	JSR	MAP_PRE_CALCULATE
	LDA	#0
	STA	REDRAW_WINDOW
	STA	TEMP_X
	STA	TEMP_Y
	STA	PRECALC_COUNT
DM01:	;FIRST CALCULATE WHERE THE BYTE IS STORED IN THE MAP
	LDY	#0
	LDA	TEMP_Y
	CLC
	ADC	MAP_WINDOW_Y	
	BPL	DMR1	;BBC: rows above/below the map repeat its edge rows
	LDA	#0
DMR1:	CMP	#64
	BCC	DMR2
	LDA	#63
DMR2:	CLC
	ROR A
	PHP
	CLC
	ADC	#>MAP
	STA	ZP3	;HIGH BYTE OF MAP SOURCE
	LDA	#$0
	PLP
	ROR A
	CLC
	ADC	TEMP_X
	ADC	MAP_WINDOW_X
	STA	ZP2	;LOW BYTE OF MAP SOURCE
	LDA	(ZP2),Y
	STA	TILE
	;NOW FIGURE OUT WHERE TO PLACE IT ON SCREEN.
	LDX	TEMP_Y
	LDA	MAP_CHART_L,X
	STA	ZP0	;LOW BYTE OF SCREEN AREA
	LDA	MAP_CHART_H,X
	STA	ZP1	;HIGH BYTE OF SCREEN AREA
	LDA	TEMP_X
	ASL A	;MULTIPLY BY 2
	CLC
	ADC	TEMP_X	;ADD ANOTHER TO MAKE X3
	ADC	ZP0
	STA	ZP0
	LDA	ZP1
	ADC	#00	;CARRY FLAG
	STA	ZP1
	;BBC: tell the HAL which plain tile is here (the tile fast path in hal_main.s), and skip the plot when it is already there
	LDX	TILE
	PHP
	SEI		;the vsync handler animates the tile data: the key (its phase) and the plot must see the same one
	JSR	HAL_TILE_KEY	;A = the tile's cache slot now (animation phase included), $FF = never cached: always plot, leave it to the cell scan
	LDY	PRECALC_COUNT
	CMP	#$FF
	BEQ	DMT0
	CMP	TILE_NEW,Y	;the same tile image was plotted here last time and nothing has touched the cells since
	BEQ	DMT4
	PHA
	JSR	PLOT_TILE
	PLA
	LDY	PRECALC_COUNT
	JMP	DMT2
DMT0:	JSR	PLOT_TILE
	LDY	PRECALC_COUNT
	LDA	#$FF
DMT2:	STA	TILE_NEW,Y
DMT4:	PLP
DMT3:
	;now check for sprites in this location
	LDA	MAP_PRECALC,Y
	CMP	#00
	BEQ	DM02
	STA	TILE
	LDA	#$FF		;BBC: an overlay is plotted on top
	STA	TILE_NEW,Y
	LDX	TEMP_Y
	LDA	MAP_CHART_L,X
	STA	ZP0	;LOW BYTE OF SCREEN AREA
	LDA	MAP_CHART_H,X
	STA	ZP1	;HIGH BYTE OF SCREEN AREA
	LDA	TEMP_X
	ASL A	;MULTIPLY BY 2
	CLC
	ADC	TEMP_X	;ADD ANOTHER TO MAKE X3
	ADC	ZP0
	STA	ZP0
	LDA	ZP1
	ADC	#00	;CARRY FLAG
	STA	ZP1
	JSR	PLOT_TRANSPARENT_TILE
DM02:	INC	TEMP_X
	INC	PRECALC_COUNT
	LDA	TEMP_X
	CMP	#11
	BEQ	DM04
	JMP	DM01
DM04:	LDA	#0
	STA	TEMP_X
	INC	TEMP_Y
	LDA	TEMP_Y
	CMP	#WIN_H
	BEQ	DM10
	JMP	DM01
DM10:	JSR	HAL_WANT_REFRESH	;BBC: the window changed: refresh at the next vsync
	JSR	DISPLAY_CURSOR
	RTS
	
;This routine plots a 3x3 tile from the tile database anywhere
;on screen.  But first you must define the tile number in the
;TILE variable, as well as the starting screen address must
;be defined in $FB.
PLOT_TILE:
	LDA	ZP0	;Grab the starting address, and adjust it for
	STA	ZP2	;the color RAM before we get started.
	LDA	ZP1
	STA	ZP3
	LDX	TILE
	;DRAW THE TOP 3 CHARACTERS
	LDA	TILE_DATA_TL,X
	LDY	#0
	STA	(ZP0),Y
	LDA	TILE_DATA_TM,X
	INY
	STA	(ZP0),Y	
	LDA	TILE_DATA_TR,X
	INY
	STA	(ZP0),Y	
	;MOVE DOWN TO NEXT LINE
	LDY	#40
	;DRAW THE MIDDLE 3 CHARACTERS
	LDA	TILE_DATA_ML,X
	STA	(ZP0),Y
	LDA	TILE_DATA_MM,X
	INY
	STA	(ZP0),Y	
	LDA	TILE_DATA_MR,X
	INY
	STA	(ZP0),Y	
	;MOVE DOWN TO NEXT LINE
	LDY	#80
	;DRAW THE BOTTOM 3 CHARACTERS
	LDA	TILE_DATA_BL,X
	STA	(ZP0),Y
	LDA	TILE_DATA_BM,X
	INY
	STA	(ZP0),Y	
	LDA	TILE_DATA_BR,X
	INY
	STA	(ZP0),Y
	;NOW DO THE COLOR
PT01:	LDA	ZP3
	SEC
	SBC	#$08	;adjust to color RAM area by SUBTRACTING $0800	
	STA	ZP3
	;DRAW THE TOP 3 COLORS
	LDA	TILE_COLOR_TL,X
	LDY	#0
	STA	(ZP2),Y
	LDA	TILE_COLOR_TM,X
	INY
	STA	(ZP2),Y	
	LDA	TILE_COLOR_TR,X
	INY
	STA	(ZP2),Y	
	;MOVE DOWN TO NEXT LINE
	LDY	#40
	;DRAW THE MIDDLE 3 COLORS
	LDA	TILE_COLOR_ML,X
	STA	(ZP2),Y
	LDA	TILE_COLOR_MM,X
	INY
	STA	(ZP2),Y	
	LDA	TILE_COLOR_MR,X
	INY
