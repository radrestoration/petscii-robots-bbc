	LDA	#06
	STA	PLAYER_DIRECTION
	JSR	DISPLAY_PLAYER_SPRITE
	JSR	DRAW_MAP_WINDOW
	LDX	UNIT
	LDA	UNIT_D,X	;get max levels
	STA	ELEVATOR_MAX_FLOOR
	;Now draw available levels on screen
	LDY	#0
	LDA	#$31
