	BNE	ELS9
	JSR	ELEVATOR_INC
	JMP	ELS5
ELS9:	CMP	#$11	;CURSOR DOWN
	BNE	ELS10
ELS9B:	JSR	SCROLL_INFO
	JSR	SCROLL_INFO
	JSR	SCROLL_INFO
	JSR	CLEAR_KEY_BUFFER
	LDA	VIC+$15	
	AND	#%11111110
	STA	VIC+$15
	RTS
ELS10:	CMP	KEY_MOVE_DOWN
	BEQ	ELS9B
