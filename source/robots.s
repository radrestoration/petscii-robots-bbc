	LDA	#$B9	;MAGNIFYING GLASS
	STA	CURSOR_ON
	JSR	USER_SELECT_OBJECT
	JSR	DISPLAY_PLAYER_SPRITE
	LDA	#1
	STA	REDRAW_WINDOW
