;This routine spaces out the timers so that not everything
;is running out once. It also starts the game_clock. 
SET_INITIAL_TIMERS:
	LDA	#1
	STA	CLOCK_ACTIVE
	LDX	#01
SIT1:	TXA
	STA	UNIT_TIMER_A,X
	LDA	#0
	STA	UNIT_TIMER_B,X
	INX	
	CPX	#48
	BNE	SIT1
	RTS

DISPLAY_PLAYER_SPRITE:
	LDA	UNIT_TILE
	CMP	#111	;Dead player
	BEQ	DSPR2
	CMP	#97
	BNE	DSPR0
	LDA	#3
	JMP	DSPR1
DSPR0:	LDA	#0
DSPR1:	STA	TEMP_A
	LDA	VIC+$15
	ORA	#%11100000	;turn on sprites 5,6,7
	STA	VIC+$15
	LDA 	#$9E
	CLC
	ADC	PLAYER_DIRECTION
	ADC	TEMP_A	
	STA	VSPTR+5	;SPRITE POINTER	sprite #5
	LDA 	#$9F	
	CLC
	ADC	PLAYER_DIRECTION
	ADC	TEMP_A	
	STA	VSPTR+6	;SPRITE POINTER	sprite #6
	LDA 	#$A0
	CLC
	ADC	PLAYER_DIRECTION
	ADC	TEMP_A		
	STA	VSPTR+7	;SPRITE POINTER	sprite #7
	RTS
DSPR2:	;display dead player
	LDA	VIC+$15
	ORA	#%11100000	;turn on sprites 5,6,7
	STA	VIC+$15
	LDA	#$B6
	STA	VSPTR+5	;SPRITE POINTER	sprite #5
	LDA	#$B7
	STA	VSPTR+6	;SPRITE POINTER	sprite #6
	LDA	#$B8
	STA	VSPTR+7	;SPRITE POINTER	sprite #7
	LDA	#02	;red
	STA	VIC+$2C	;SPRITE COLOR 5
	LDA	#10	;orange
	STA	VIC+$2D	;SPRITE COLOR 6
	LDA	#15	;light gray
	STA	VIC+$2E	;SPRITE COLOR 7
	RTS

