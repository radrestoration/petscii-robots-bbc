;This is the routine that runs every 60 seconds from the IRQ.
;BGTIMER1 is always set to 1 every cycle, after which the main
;program will reset it to 0 when it is done with it's work for
;that cycle.  BGTIMER2 is a count-down to zero and then stays
;there.
RUNIRQ:	LDA	MUSIC_STATE
	CMP	#0
	BEQ	IRQ0
	JSR	HAL_MUSIC_TICK	;music play routine
IRQ0:	JSR	UPDATE_GAME_CLOCK
	JSR	ANIMATE_WATER
	LDA	#1
	STA	BGTIMER1
	LDA	BGTIMER2
	CMP	#0
	BEQ	IRQ1
	DEC	BGTIMER2
IRQ1:	LDA	KEYTIMER
	CMP	#0
	BEQ	IRQ2
	DEC	KEYTIMER
IRQ2:	;BORDER FLASHER
	LDX	BORDER
	CPX	#0
	BEQ	IRQ3
	LDA	BORDER,X
	STA	VIC+$20
	DEC	BORDER
	;BACKGROUND FLASHER
IRQ3:	LDX	BGFLASH
	CPX	#0
	BEQ	IRQ10
	LDA	BGFLASH,X
	STA	VIC+$21
	DEC	BGFLASH
IRQ10:	;SCREEN_SHAKER
	LDA	SCREEN_SHAKE
	CMP	#$00
	BEQ	SHAKE4
SHAKE2:	INC	SSCOUNT
	LDA	SSCOUNT
	CMP	#5
	BNE	SHAKE3
	LDA	#0
	STA	SSCOUNT
SHAKE3:	LDY	SSCOUNT
	LDA	VIC+$16
	AND	#%11111000
	ORA	SSHAKE,Y
	STA	VIC+$16
	JMP	IRQ20
SHAKE4:	LDA	#%11001000
	STA	VIC+$16
	;CHECK TO SEE IF KEYBOARD WAS DISABLED	
	;This routine causes the kernal to skip keyboard
	;input for one cycle to help "debounce" the 
	;keyboard.
IRQ20:	LDA	KBDENABLE	;1=normal 0=disabled
	CMP	#0
	BNE	IRQ30
	LDA	KEYSOFF
	CMP	#00
	BEQ	IRQ21
	LDA	#0
	STA	KEYSOFF
	LDA	#1
	STA	KBDENABLE	;turn keyboard back on
	JMP	IRQ30
IRQ21:	INC	KEYSOFF
IRQ30:	;Animate Sprite Color
	DEC	SPRITECOLTIMER
	LDA	SPRITECOLTIMER
