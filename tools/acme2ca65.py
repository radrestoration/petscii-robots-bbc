#!/usr/bin/env python3
"""Mechanical ACME -> ca65 translation for the PETSCII Robots sources.
Only the ACME features the sources really use (checked by grep): !BYTE, !PET, !SCR,
!SOURCE, !to, *=, labels without colons, bare ASL/LSR/ROL/ROR.
!SCR: lower case a-z -> 1..26, everything else unchanged (verified against the
compiled Plus4 PRG).  !PET: ASCII -> PETSCII (a-z -> $41.., A-Z -> $C1..).
usage: acme2ca65.py in.asm out.s"""
import re, sys

def scr(c):  return ord(c) - 96 if 'a' <= c <= 'z' else ord(c)
def pet(c):
    if 'a' <= c <= 'z': return ord(c) - 32
    if 'A' <= c <= 'Z': return ord(c) + 128
    return ord(c)

def split_items(s):
    """split a data operand list on commas outside of quotes"""
    out, cur, q = [], '', False
    for ch in s:
        if ch == '"': q = not q
        if ch == ',' and not q: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur); return out

def data(kind, rest):
    conv = {'BYTE': None, 'SCR': scr, 'PET': pet}[kind]
    items = []
    for it in split_items(rest):
        it = it.strip()
        if it.startswith('"'):
            items += [str(conv(c)) for c in it.strip('"')]
        elif it: items.append(it)
    return '.byte ' + ','.join(items)

LABEL = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)(:?)(.*)$')
SHIFT = re.compile(r'^(\s*)(ASL|LSR|ROL|ROR)(\s*)(;.*)?$', re.I)
DIR = re.compile(r'^(\s*)!(BYTE|SCR|PET)\s*(.*?)(\s*;.*)?$', re.I)

def main(src, dst):
    out = ['; Generated by tools/acme2ca65.py from ' + src.split('/')[-1] + ' - do not edit',
           '.feature labels_without_colons', '']
    for line in open(src, errors='replace').read().replace('\r', '').split('\n'):
        s = line
        if re.match(r'^\s*!to\b', s, re.I): continue
        if re.match(r'^\s*\*\s*=', s): s = '; ' + s; out.append(s); continue
        m = re.match(r'^\s*!SOURCE\s+"([^"]+)"', s, re.I)
        if m: out.append('.include "%s"' % m.group(1)); continue
        # label split so the directive/instruction handling sees the rest
        m = LABEL.match(s)
        lab = ''
        if m and not re.match(r'^(ASL|LSR|ROL|ROR)\b', s, re.I):
            lab, rest = m.group(1), m.group(3)
            if rest.strip() == '' or rest.lstrip()[0] in ';!' or re.match(r'^\s*[A-Za-z]{3}\b', rest) or rest.lstrip().startswith('='):
                s = rest if rest.lstrip().startswith('=') else rest
            else:
                lab = ''
        s = re.sub(r'^(\s*(?:JMP|JSR)\s+[A-Za-z_0-9]+):', r'\1', s)   # ACME tolerates 'JMP LABEL:'
        d = DIR.match(s)
        if d: s = d.group(1) + data(d.group(2).upper(), d.group(3)) + (d.group(4) or '')
        sh = SHIFT.match(s)
        if sh: s = sh.group(1) + sh.group(2) + ' A' + sh.group(3) + (sh.group(4) or '')
        if lab:
            s = lab + (' =' + s.lstrip()[1:] if s.lstrip().startswith('=') else ':' + s)
        out.append(s)
    open(dst, 'w').write('\n'.join(out) + '\n')

main(sys.argv[1], sys.argv[2])
