"""Convert the C64 assets into BBC disc files in build/data/:
  font.bin    256 x 8-byte 1-bit glyphs (incbin'd into the sideways-RAM image)
  sprites.bin 43 x 64-byte C64 sprites (loaded as-is, converted at draw time)
  tiles.bin   tileset.gfx without its load address (5 pages x 4 .. 20 pages, 5120 B) + the 256-byte tile cache slot table (TSLOT)
  levelX.bin  level files without load address ($300 unit bytes + 8 KB map)
  palette.inc ca65 include: PHYS (4 BBC colours), CMAP (C64 colour -> logical 0..3), CMASK (-> pixel mask)
usage: make_data.py [upstream/c64 dir] [out dir]"""
import sys, os, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import c64data
U = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'upstream', 'c64')
O = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'build', 'data')
os.makedirs(O, exist_ok=True)
w = lambda n, b: open(os.path.join(O, n), 'wb').write(b)
w('font.bin', c64data.load_font(U))
sp = open(f'{U}/sprites.gfx', 'rb').read()[2:]
assert len(sp) == 43 * 64, len(sp)
w('sprites.bin', sp)
ts = c64data.load_tileset(U)
# Tile cache slots: tiles whose nine character/colour cells are identical share one cached image (the tile cache in the sideways
# banks holds one image per slot).  The tiles the game rewrites at run time (ANIMATE_WATER in robots.s: STA TILE_DATA_xx+n) cycle
# through a few images, one step per animation tick, so each phase gets its own slot: slot = TSLOT[id] + the current phase of its
# kind (TILEKIND: 2 = period 3, 3 = period 2; tools/anim_test.py checks the periods against the game's own routine).  The cinema
# screen (tiles 20-22) scrolls a 197-step message and is never cached (TSLOT 255: the key $FF means "draw cell by cell").
# TSLOT[id] -> first slot, appended to tiles.bin at &9400 of the data bank; TILEKIND goes to tile_kind.inc.
PHASED = {204: 3, 221: 3, 148: 3, 196: 2, 197: 2, 200: 2, 201: 2, 143: 2}
UNCACHED = {20, 21, 22}
KIND_OF_PERIOD = {3: 2, 2: 3}
_ch, _co = c64data.tile_tables(ts)
_key = lambda t: (tuple(int(_ch[k][t]) for k in range(9)), tuple(int(_co[k][t]) & 15 for k in range(9)))
_seen = {}; tslot = []; tkind = []; nslot = 0
for t in range(256):
    if t in UNCACHED: tslot.append(255); tkind.append(1)
    elif t in PHASED: tslot.append(nslot); nslot += PHASED[t]; tkind.append(KIND_OF_PERIOD[PHASED[t]])
    else:
        k = _key(t)
        if k not in _seen: _seen[k] = nslot; nslot += 1
        tslot.append(_seen[k]); tkind.append(0)
assert len(ts) == 0x1400 and nslot <= 254
w('tiles.bin', ts + bytes(tslot))
w('tile_meta.inc', ('; generated by make_data.py\nTILE_SLOTS = %d       ; cache slots (distinct tile images, and every phase of the animated tiles)\n' % nslot).encode())
w('tile_kind.inc', ('; generated by make_data.py: 0 plain, 1 never cached, 2 animated with period 3, 3 animated with period 2\nTILEKIND:\n' + ''.join('        .byte ' + ','.join(map(str, tkind[i:i + 16])) + '\n' for i in range(0, 256, 16))).encode())
for f in sorted(glob.glob(f'{U}/level-?')):
    d = open(f, 'rb').read()[2:]
    assert len(d) == 0x300 + 0x2000, (f, len(d))
    w('level%s.bin' % f[-1].upper(), d)
# the game screen: the C64's 40x25 layout with 6 rows inserted below row 20 (taller window), as compressed bytes
import re
src = open(f'{U}/C64ROBOTS.ASM', errors='replace').read().replace('\r', '').split('\n')
def grab(label, nxt):
    i = [k for k, l in enumerate(src) if l.startswith(label)][0]; j = [k for k, l in enumerate(src) if l.startswith(nxt)][0]; out = []
    for l in src[i:j]:
        m = re.search(r'!BYTE\s+(.*)$', l.split(';')[0], re.I)
        if m: out += [int(x.strip().lstrip('$'), 16) if x.strip().startswith('$') else int(x.strip()) for x in m.group(1).split(',') if x.strip()]
    return out
def rle_dec(data, n):
    out, i = [], 0
    while len(out) < n:
        if data[i] == 96: out += [data[i+1]] * (data[i+2] + 1); i += 3
        else: out.append(data[i]); i += 1
    return out
def rle_enc(cells):                 # the game's format: 96,value,count-1 for runs (and for a literal 96)
    out, i = [], 0
    while i < len(cells):
        v, n = cells[i], 1
        while i + n < len(cells) and cells[i+n] == v and n < 256: n += 1
        if n >= 4 or v == 96: out += [96, v, n - 1]
        else: out += [v] * n
        i += n
    return out
def tall(cells, blank):             # rows 0-20 as is; 6 more copies of row 20 (window / empty panel); old rows 21-24 (info, health) below; blank row 31
    rows = [cells[r*40:(r+1)*40] for r in range(25)]
    return sum(rows[:21] + [rows[20]] * 6 + rows[21:25] + [[blank] * 40], [])
for name, nxt, blank in (('SCR_TEXT', 'SCR_COLOR', 32), ('SCR_COLOR', 'SCR_ENDGAME', 0xF1)):
    cells = tall(rle_dec(grab(name, nxt), 1000), blank); enc = rle_enc(cells); assert rle_dec(enc, 1280) == cells
    open(os.path.join(O, name.lower() + '.inc'), 'w').write('\n'.join('\t.byte ' + ','.join(map(str, enc[k:k+16])) for k in range(0, len(enc), 16)) + '\n')
pal, cmap = c64data.choose_palette(U)
mask = [0, 0x0F, 0xF0, 0xFF]
with open(os.path.join(O, 'palette.inc'), 'w') as f:
    f.write('; generated by tools/make_data.py - first-pass palette, re-tune later\n')
    f.write('PHYS:  .byte %s\n' % ','.join(map(str, pal)))
    f.write('CMAP:  .byte %s\n' % ','.join(map(str, cmap)))
    f.write('CMASK: .byte %s\n' % ','.join('$%02X' % mask[c] for c in cmap))
print('palette', pal, 'cmap', cmap)
