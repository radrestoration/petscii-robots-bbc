"""Convert the Plus4 version's sound effects (TED: 10-bit register, volume 0-8, bit 5 tone / bit 6 noise) for the BBC's SN76489
and write build/data/sound.inc.  The C64's SID effect data is a format of the SID driver in music.c64 (not decoded here); the Plus4
data is documented in its SOUND.ASM and the game's 18 effects exist there.
Conversions (pitch is from the TED documentation as remembered - check by ear):
  TED frequency  f = 110840 / (1024 - reg)   Hz   (PAL)
  SN76489 period N = 125000 / f              (BBC: 4 MHz / 32)  =>  N = 1.1277 * (1024 - reg): linear, so a TED frequency step of s
                                                                     registers is a period step of -1.1277 * s
  volume: TED 0-8 (higher values act as 8) -> 0-15 loudness
Note record (little endian), one per note:
  N lo | N hi (bits 0-1) + $40 if noise | loudness (0-15) + $80 if this record ends the effect | timer (frames) + $80 if a step follows
  [step lo | step hi (signed period change per step) | step count ($FF = fade out)]
Also writes the C64 sound id -> effect table with priorities (the Plus4 numbers: larger = more important).
usage: make_sound.py [Plus4 dir] [out dir]"""
import os, re, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U = sys.argv[1] if len(sys.argv) > 1 else f'{R}/upstream/Plus4'
O = sys.argv[2] if len(sys.argv) > 2 else f'{R}/build/data'
os.makedirs(O, exist_ok=True)
src = open(f'{U}/SOUND.ASM', errors='replace').read().replace('\r', '').split('\n')
prio = {m.group(1): int(m.group(2), 16) for l in src for m in [re.match(r'(SOUND_[A-Z0-9_]+)\s*=\s*\$([0-9A-Fa-f]+)', l)] if m}
data = {}; cur = None
for l in src:
    m = re.match(r'(SOUND_DATA_[A-Z0-9_]+):', l)
    if m: cur = m.group(1); data[cur] = []; continue
    m = re.search(r'!BYTE\s+(.*?)(;.*)?$', l)
    if cur and m and not l.startswith('SOUND_FX'):
        data[cur] += [int(x.strip().lstrip('$'), 16) for x in m.group(1).split(',') if x.strip()]
    elif cur and l.strip() and not l.startswith((' ', '\t', ';')): cur = None
def period(reg): return max(8, min(1023, round(1.1277 * (1024 - reg))))
def convert(b):
    out = []; i = 0
    while i < len(b):
        reg = ((b[i+1] & 3) << 8) | b[i]; vw = b[i+2]; i += 3
        n = period(reg); noise = 0x40 if vw & 0x40 else 0
        vol = ((min(vw & 15, 8) * 15) + 4) // 8
        if vw == 0:                                   # end of effect
            out += [n & 255, (n >> 8) | noise, 0x80]; break
        t = b[i]; i += 1
        if t & 0x80:
            step = b[i]; cnt = b[i+1]; i += 2
            ds = -round(1.1277 * ((step & 0x7F) * (-1 if step & 0x80 else 1)))          # +reg = shorter period
            out += [n & 255, (n >> 8) | noise, vol, (t & 0x7F) | 0x80, ds & 255, (ds >> 8) & 255, cnt]
        else:
            out += [n & 255, (n >> 8) | noise, vol, t]
    return out
# C64 sound ids (the C64 version's table) -> Plus4 effect
C64 = [('EXPLOSION', 'explosion'), ('EXPLOSION', 'explosion'), ('MEDKIT', 'medkit'), ('EMP', 'emp'), ('MAGNET', 'magnet'),
       ('SHOCK', 'electric shock'), ('MOVEOBJ', 'move object'), ('SHOCK', 'electric shock'), ('PLASMA', 'plasma gun'),
       ('PISTOL', 'fire pistol'), ('ITEM_FOUND', 'item found'), ('ERROR', 'error'), ('CYCLE_ITEM', 'change weapons'),
       ('CYCLE_ITEM', 'change items'), ('DOOR', 'door'), ('MENU_BEEP', 'menu beep'), ('WALK', 'walk'), ('BEEP', 'short beep'),
       ('BEEP', 'short beep')]
names = sorted({n for n, _ in C64})
lines = ['; generated by tools/make_sound.py from the Plus4 version\'s sound data']
for n in names:
    lines.append('SND_%s:' % n + '\t.byte ' + ','.join(str(x) for x in convert(data['SOUND_DATA_' + n])))
lines.append('SND_FX_L:\t.byte ' + ','.join('<SND_%s' % n for n, _ in C64))
lines.append('SND_FX_H:\t.byte ' + ','.join('>SND_%s' % n for n, _ in C64))
lines.append('SND_PRIO:\t.byte ' + ','.join(str(prio['SOUND_' + n]) for n, _ in C64))
open(f'{O}/sound.inc', 'w').write('\n'.join(lines) + '\n')
print('sound.inc:', sum(len(convert(data['SOUND_DATA_' + n])) for n in names), 'bytes of notes for', len(names), 'effects')
