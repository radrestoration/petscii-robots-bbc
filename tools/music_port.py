"""Translate the C64 version's music player (upstream/c64/music.c64: a stripped GoatTracker 2 play routine at $A000, SID) into
ca65 source for the BBC build, so the real player logic and the real song data are what plays.

music.c64 is a PRG loaded at $A000:  $A000-$A3D8 play routine (only $A119-$A3D8 runs per frame; $A3D9-$A441 is the SID sound-effect
path, which this port drops - the effects are the Plus4 version's, see make_sound.py), $A442-$A9B4 tables and variables,
$A9B5-$C8C9 order lists and patterns.  Which bytes are which was established by running the original in the simulator
(tools/sim6502.py) and from the code itself; nothing is guessed - tools/music_test.py checks the translation against the original.

What this script writes (build/data/):
  music_core.inc   the translated routine.  Every instruction keeps its place inside its 256-byte page, because the player patches the
                   low byte of a JSR operand ($A26D/$A276 <- table $A442) to dispatch the commands in page $A0.  Operands that
                   pointed at the SID ($D400-$D418) point at the shadow registers SIDSH; the variable/table block at $A442 is TB;
                   zero page $3E/$3F are MZP.  The code is emitted as one block starting on a page boundary.
  music_tab.inc    the shared tables ($A442-$A9B4) minus the song-specific pointer tables.
usage: music_port.py [upstream c64 dir] [out dir]      (translate; also writes music_meta.inc)
       music_port.py songs <robots.dbg> <out dir>     (after linking: write the per-song images MUSn)"""
import os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(R, 'tools'))
from sim6502 import MODES

BASE = 0xA000
CODE_END = 0xA3D9           # first byte after the play routine
SFX_START = 0xA3D9          # $A3D9-$A441: SID sound effects (dropped)
TAB_START, TAB_END = 0xA442, 0xA9B5       # order lists start at $A9B5 (the speed table's second column ends there)
LEN = {'imp': 1, 'acc': 1, 'imm': 2, 'zp': 2, 'zpx': 2, 'zpy': 2, 'rel': 2, 'izx': 2, 'izy': 2}

def load(u):
    d = open(os.path.join(u, 'music.c64'), 'rb').read()
    assert d[0] | d[1] << 8 == BASE
    return d[2:]

def decode(d):
    """linear disassembly of $A000-$A3D8 -> [(addr, opcode, name, mode, operand bytes)]"""
    out = []; a = BASE
    while a < CODE_END:
        c = d[a - BASE]
        assert c in MODES, 'illegal opcode %02X at %04X' % (c, a)
        n, m, _ = MODES[c]; ln = LEN.get(m, 3)
        out.append((a, c, n, m, d[a - BASE + 1:a - BASE + ln]))
        a += ln
    assert a == CODE_END, 'code does not end on an instruction boundary'
    return out

def translate(ins):
    starts = {i[0]: i for i in ins}
    def where(v):
        """symbolic expression for C64 address v"""
        if 0xD400 <= v <= 0xD418: return 'SIDSH+%d' % (v - 0xD400)
        if BASE <= v < CODE_END:
            if v in starts: return 'c_%04X' % v
            s = max(a for a in starts if a < v)                  # inside an instruction (self-modified operand)
            return 'c_%04X+%d' % (s, v - s)
        if v == 0xA582: return 'MORDLO'          # order-list pointers (one song's three channels)
        if v == 0xA59A: return 'MORDHI'
        if v == 0xA5B2: return 'MPATLO'          # pattern pointers (renumbered per song)
        if v == 0xA653: return 'MPATHI'          # (the table's last entry, $A6F3, is also the base of the next table: TB2)
        if TAB_START <= v < 0xA582:       return 'TB1+%d' % (v - TAB_START)
        if 0xA6F3 <= v < TAB_END:         return 'TB2+%d' % (v - 0xA6F3)
        raise ValueError('unmapped operand $%04X' % v)
    L = ['; generated by tools/music_port.py from upstream/c64/music.c64 - do not edit', '.align 256', 'MUSIC_CORE:']
    for a, c, n, m, o in ins:
        lab = 'c_%04X:' % a
        if m in ('imp', 'acc'): t = n + (' a' if m == 'acc' else '')
        elif m == 'imm': t = '%s #$%02X' % (n, o[0])
        elif m in ('zp', 'zpx', 'zpy'):
            v = o[0]; assert v in (0x3E, 0x3F), 'zero page $%02X' % v
            t = '%s MZP+%d%s' % (n, v - 0x3E, {'zp': '', 'zpx': ',x', 'zpy': ',y'}[m])
        elif m in ('izx', 'izy'):
            v = o[0]; assert v == 0x3E
            t = '%s (MZP%s' % (n, ',x)' if m == 'izx' else '),y')
        elif m == 'rel':
            v = o[0]; tgt = a + 2 + (v - 256 if v > 127 else v); t = '%s c_%04X' % (n, tgt)
        else:
            v = o[0] | o[1] << 8
            t = '%s %s%s' % (n, where(v), {'abs': '', 'abx': ',x', 'aby': ',y', 'ind': ''}[m])
            if m == 'ind': t = '%s (%s)' % (n, where(v))
        L.append('%-9s%s' % (lab, t))
    return L

def parse_songs(d):
    """per song: its three order lists (bytes up to and including the $FF and loop byte) and the patterns they use.
    Order list entries are pattern numbers; patterns are packed back to back in address order, so a pattern ends where the next
    one starts (checked: tools/music_test.py plays the repacked songs against the original)."""
    ol = [d[0xA582 - BASE + i] | d[0xA59A - BASE + i] << 8 for i in range(24)]
    pt = [d[0xA5B2 - BASE + i] | d[0xA653 - BASE + i] << 8 for i in range(161)]
    starts = sorted(pt); end = BASE + len(d)
    def pat(i):
        a = pt[i]; b = next((x for x in starts if x > a), end)
        return bytes(d[a - BASE:b - BASE])
    songs = []
    for s in range(8):
        lists = []; used = []
        for c in range(3):
            a = ol[s * 3 + c]; o = bytearray()
            while d[a - BASE] != 0xFF: o.append(d[a - BASE]); a += 1
            o += bytes([0xFF, d[a + 1 - BASE]])
            lists.append(bytes(o))
            for b in o[:-2]:
                if b not in used: used.append(b)
        songs.append((lists, used, [pat(i) for i in used]))
    return songs

def pack_song(song, np_, r2, r2_end):
    """-> bytes: header (pointer tables) + order lists + patterns, to be loaded at r2"""
    lists, used, pats = song
    renum = {u: i for i, u in enumerate(used)}
    assert len(used) <= np_
    pos = r2 + 6 + 2 * np_; body = bytearray(); ola = []; pa = []
    for l in lists:
        ola.append(pos + len(body)); body += bytes(renum.get(b, b) if k < len(l) - 2 else b for k, b in enumerate(l))
    for p in pats: pa.append(pos + len(body)); body += p
    assert pos + len(body) <= r2_end, 'song does not fit (%d bytes over)' % (pos + len(body) - r2_end)
    h = bytearray(6 + 2 * np_)
    for c in range(3): h[c] = ola[c] & 255; h[3 + c] = ola[c] >> 8
    for i, a in enumerate(pa): h[6 + i] = a & 255; h[6 + np_ + i] = a >> 8
    return bytes(h) + bytes(body)

def main():
    u = sys.argv[1] if len(sys.argv) > 1 else os.path.join(R, 'upstream', 'c64')
    o = sys.argv[2] if len(sys.argv) > 2 else os.path.join(R, 'build', 'data')
    os.makedirs(o, exist_ok=True)
    d = load(u)
    ins = decode(d)
    # the branch to the SID sound-effect path ($A3A9: ldy $A4AF,x / bne $A3D9) - effects are not ported
    for k, i in enumerate(ins):
        if i[0] == 0xA3AB: assert ins[k - 1][0] == 0xA3A9 and ins[k - 2][0] == 0xA3A6
    ins = [i for i in ins if i[0] not in (0xA3A9,)]
    open(os.path.join(o, 'music_core.inc'), 'w').write('\n'.join(translate(ins)) + '\n')
    def bytes_lines(label, blob):
        L = [label + ':']
        for k in range(0, len(blob), 16): L.append('        .byte ' + ','.join('$%02X' % b for b in blob[k:k + 16]))
        return L
    # Note numbers reach 127 (wave-table notes are added to the base note and masked with $7F) but the frequency table has 96
    # entries: the C64 player reads on, past the end of the high-byte table, into the next 32 bytes ($A582-$A5A1: its order list
    # pointers).  Songs 0, 3 and 4 do this, so those 32 bytes are kept to make the notes sound as on the C64.
    lines = ['; generated by tools/music_port.py: the music tables of the C64 player ($A442-$A9B4) verbatim, minus the song pointer tables']
    lines += bytes_lines('TB1', d[TAB_START - BASE:0xA5A2 - BASE]) + bytes_lines('TB2', d[0xA6F3 - BASE:TAB_END - BASE])
    open(os.path.join(o, 'music_tab.inc'), 'w').write('\n'.join(lines) + '\n')
    songs = parse_songs(d)
    np_ = max(len(s[1]) for s in songs)
    open(os.path.join(o, 'music_meta.inc'), 'w').write('; generated by tools/music_port.py\nMUS_NP = %d       ; patterns in the biggest song (pointer table size)\n' % np_)
    print('music_core.inc: %d instructions; music_tab.inc: %d bytes; MUS_NP = %d' % (len(ins), TAB_END - TAB_START - (0xA6F3 - 0xA582), np_))
    for k, s in enumerate(songs): print('  song %d: %d patterns, order lists %d bytes, patterns %d bytes' % (k, len(s[1]), sum(map(len, s[0])), sum(map(len, s[2]))))

def songs_main(lbl, o):
    """after linking: write the song images for the address the build chose (MUS_R2 in the debug file)"""
    sym = {}
    for l in open(lbl):                                     # ld65 --dbgfile: sym id=..,name="X",...,val=0x....
        if l.startswith('sym') and 'name="' in l and 'val=0x' in l:
            sym[l.split('name="')[1].split('"')[0]] = int(l.split('val=0x')[1].split(',')[0], 16)
    r2 = sym['MUS_R2']; np_ = sym['MUS_NP']
    d = load(os.path.join(R, 'upstream', 'c64'))
    for k, s in enumerate(parse_songs(d)):
        b = pack_song(s, np_, r2, 0xC000)
        open(os.path.join(o, 'MUS%d' % k), 'wb').write(b)
        print('MUS%d  &%04X  %d bytes' % (k, r2, len(b)))

if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'songs': songs_main(sys.argv[2], sys.argv[3])
    else: main()
